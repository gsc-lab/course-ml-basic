"""
Statlog Heart 데이터셋 살펴보기 — 심장병 유무를 예측하는 이진 분류 문제
05번까지는 유방암 데이터로 로지스틱 회귀의 학습과 평가 과정을 살펴봤다.
이번에는 심장병 데이터로 특성의 종류와 오답의 비용을 살펴보고,
학습 데이터가 적을 때 모델의 성능과 과적합 양상이 어떻게 달라지는지 알아본다.
이 파일에서는 데이터를 탐색하고 분할한다. 모델 학습은 다음 실습에서 진행한다.

Statlog Heart 데이터셋 (UCI Machine Learning Repository)
  270명의 검사 기록으로, 각 기록에는 13개의 특성과 심장병 유무 라벨이 있다.
  심장병이 있는 사람과 없는 사람의 기록이 모두 포함되어 있으며, 결측치는 없다.
  특성에는 나이·혈압·콜레스테롤처럼 익숙한 항목부터
  심전도 ST 분절, 탈륨 스캔처럼 심장내과 검사 항목까지 섞여 있다.

  → 풀어야 할 문제: "13개의 특성으로 심장병 유무를 예측할 수 있을까?"

왜 이 데이터로 실습하나?
  1) 데이터가 적다: 60%를 학습용으로 나누면 162건이다.
     가중치 w 13개와 편향 b 1개를 학습하며, 검증 손실로 과적합 여부를 확인할 수 있다.
     과적합의 정도와 검증 손실이 가장 낮아지는 시점은 분할과 학습 설정에 따라 달라진다.
  2) 오답을 분석하기 좋다: 심장병을 놓친 경우와 없는 병을 있다고 예측한 경우를
     구분하면, 정확도만으로 알 수 없는 모델의 한계를 살펴볼 수 있다.
  3) 특성의 의미가 구체적이다: 가중치의 부호를 통해 각 특성이 예측에 미치는
     방향을 살펴볼 수 있다. 다만 가중치가 질병의 원인이나 의학적 중요도를 뜻하지는 않는다.
  4) 특성의 종류가 섞여 있다: 수치형, 이진형, 순서형, 명목형 특성이 함께 있다.
     이번 실습에서는 모두 숫자로 사용하며, 그 한계는 아래 2번에서 설명한다.
  5) 심장병 있음(present)을 1로 변환한다: 유방암 예제의 1(양성종양)과 의미가 다르다.
     라벨 1의 의미를 확인하는 습관을 들이기 좋다.
  6) 공식 설명문에 오답의 상대적 비용이 제시되어 있다: 심장병을 놓치면 5,
     없는 심장병을 있다고 예측하면 1이다. 재현율과 오답의 비용을 함께 살펴볼 수 있다.

OpenML 이란?
  OpenML(openml.org)은 공개 데이터셋을 공유하는 온라인 플랫폼이다.
  sklearn.datasets.fetch_openml()로 데이터와 설명을 불러올 수 있다.
  최초 다운로드에는 인터넷 연결이 필요하다. 기본 설정에서는 내려받은 데이터를
  사용자 홈 폴더의 scikit_learn_data에 캐시하여 다음 실행에서 재사용한다.

데이터셋 설명: https://archive.ics.uci.edu/dataset/145/statlog+heart
"""
import numpy as np
from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split

# ============================================================
# 1. 데이터 불러오기
#    as_frame=True: 특성은 pandas DataFrame, 라벨은 pandas Series로 받는다.
#    열 이름으로 특성을 확인하고, NumPy로 학습할 때는 .to_numpy()로 변환한다.
#    version=1: 이름이 같은 데이터셋 중 사용할 버전을 지정한다.
# ============================================================
ds = fetch_openml("heart-statlog", version=1, as_frame=True)
X_df, y_raw = ds.data, ds.target

print("데이터셋 객체(Bunch)에 포함된 항목:", list(ds.keys()))
print(f"입력 X의 형태: {X_df.shape}  (행=검사 기록 수, 열=특성 수)")
print(f"원본 라벨 y의 형태: {y_raw.shape}  라벨 종류: {list(y_raw.unique())}")
# print(ds.DESCR)   # 공식 설명문 — 특성 설명과 비용 행렬이 실려 있다

# ============================================================
# 2. 특성(feature) 13개
#    공식 문서의 구분: 수치형 6개, 이진형 3개, 순서형 1개, 명목형 3개.
#    수치형에는 혈관 수처럼 정수로 기록된 특성도 포함된다.
#    명목형은 순서 없는 범주, 순서형은 순서가 있는 범주를 뜻한다.
#    아래 표에 OpenML의 열 이름, 한국어 설명, 특성 종류를 정리한다.
# ============================================================
FEATURES = {
    #  열 이름                                 한국어 뜻                               종류
    "age":                                  ("나이 (세)",                              "수치형"),
    "sex":                                  ("성별 (0=여성, 1=남성)",                  "이진형"),
    "chest":                                ("흉통 유형 (1~4: 유형 코드)",              "명목형"),
    "resting_blood_pressure":               ("안정 시 혈압 (mmHg)",                     "수치형"),
    "serum_cholestoral":                    ("혈청 콜레스테롤 (mg/dL)",                 "수치형"),
    "fasting_blood_sugar":                  ("공복 혈당 > 120 mg/dL (0=아니오, 1=예)",  "이진형"),
    "resting_electrocardiographic_results": ("안정 시 심전도 결과 (0~2: 유형 코드)",     "명목형"),
    "maximum_heart_rate_achieved":          ("운동 중 최대 심박수 (회/분)",              "수치형"),
    "exercise_induced_angina":              ("운동 유발 협심증 (0=없음, 1=있음)",        "이진형"),
    "oldpeak":                              ("안정 시 대비 운동 시 ST 분절 하강 정도",    "수치형"),
    "slope":                                ("최대 운동 시 ST 분절 기울기 (1~3)",       "순서형"),
    "number_of_major_vessels":              ("형광투시로 확인한 주요 혈관 수 (0~3)",     "수치형"),
    "thal":                                 ("탈륨 검사 (3=정상, 6=고정 결손, 7=가역 결손)", "명목형"),
}

print("\n특성별 설명 (열 이름 | 종류 | 의미):")
for name, (korean, kind) in FEATURES.items():
    print(f"  {name:38s} | {kind} | {korean}")

# 명목형 특성의 숫자는 크기가 아니라 범주를 나타내는 코드다.
#   chest=4가 chest=1의 네 배를 뜻하거나, thal=7이 thal=3보다 높은 등급을 뜻하지 않는다.
#   숫자 그대로 x·w를 계산하면 범주 사이에 수치적 순서와 간격이 있다고 가정하게 된다.
#   원-핫 인코딩은 범주별로 0/1 열을 만들어 이런 가정을 피하는 방법이다.
#   이번 실습에서는 기존 학습 코드와 연결하기 위해 숫자를 그대로 사용한다.
#   순서형 특성도 코드 사이의 간격까지 같다고 볼 수 있는지는 따로 검토해야 한다.

# ============================================================
# 3. 정답(label) — 문자열을 0/1 로 바꾼다
#      "absent"  → 0 (심장병 없음)
#      "present" → 1 (심장병 있음)  ← 관심 클래스(positive class)
#    OpenML 버전의 문자열 라벨을 변환한다. UCI 원본의 숫자 라벨(1/2)과 구분한다.
#    이진 분류용 precision_score/recall_score의 기본값은 pos_label=1이다.
#    여기서는 심장병 있음을 평가한다. 유방암 예제에서 암(0)을 평가하려면 pos_label=0이다.
#    classification_report는 각 클래스의 정밀도와 재현율을 모두 보여준다.
# ============================================================
y = (y_raw == "present").astype(int).to_numpy()
X = X_df.to_numpy(dtype=float)

print("\n변환한 라벨별 기록 수와 비율:")
for label, name in [(0, "absent (심장병 없음)"), (1, "present (심장병 있음)")]:
    count = np.sum(y == label)
    print(f"  y={label}  {name}: {count:3d}건 ({100 * count / len(y):.1f}%)")

# ============================================================
# 4. 특성마다 단위와 값의 범위가 다르다 — 표준화가 필요한 이유
#    콜레스테롤은 수백 단위, oldpeak은 한 자릿수, 성별은 0/1로 기록된다.
#    표준화는 (값 - 평균) / 표준편차로 계산하며, 경사하강법의 안정적인 학습에 도움이 된다.
#    이 실습에서는 0/1 특성도 함께 표준화할 수 있다. 범주형 인코딩을 대신하는 것은 아니다.
#    실제 표준화는 분할 후 학습 데이터의 평균과 표준편차만 사용해 수행한다.
# ============================================================
print("\n일부 특성의 최솟값과 최댓값 (전체 데이터 기준):")
for name in ["age", "serum_cholestoral", "oldpeak", "sex"]:
    col = X_df[name]
    print(f"  {name:20s} {col.min():7.1f} ~ {col.max():7.1f}")

# ============================================================
# 5. 심장병 유무에 따라 특성의 평균이 다를까?
#    이 데이터에서는 심장병 있음 그룹의 평균 최대 심박수가 더 낮고,
#    운동 유발 협심증, 주요 혈관 수, oldpeak의 평균은 더 높다.
#    0/1 특성의 평균은 값이 1인 기록의 비율이다. 예: 협심증 평균 0.5 = 있음 50%.
#    평균 차이는 탐색의 출발점이다. 질병의 원인이나 개별 기록의 진단 기준은 아니다.
#    특성마다 단위가 다르므로 평균 차이의 크기만으로 중요도를 비교할 수도 없다.
# ============================================================
print("\n심장병 유무에 따른 일부 특성의 평균:")
print("  absent(0)=심장병 없음, present(1)=심장병 있음")
print(f"  {'특성':28s} {'absent(0)':>10s} {'present(1)':>10s}")
for name in ["maximum_heart_rate_achieved", "exercise_induced_angina",
             "number_of_major_vessels", "oldpeak", "serum_cholestoral"]:
    m0 = X_df.loc[y == 0, name].mean()
    m1 = X_df.loc[y == 1, name].mean()
    print(f"  {name:30s} {m0:10.2f} {m1:10.2f}")

# ============================================================
# 6. 오답의 비용 — 공식 설명문(ds.DESCR)에 실린 비용 행렬
#
#                     예측 absent   예측 present
#      실제 absent          0             1        ← 없는 심장병을 있다고 예측(FP): 비용 1
#      실제 present         5             0        ← 있는 심장병을 없다고 예측(FN): 비용 5
#
#    심장병을 놓친 오답에 다섯 배의 상대적 비용을 부여한다. 실제 금액을 뜻하지는 않는다.
#    따라서 정확도와 함께 present(1)의 재현율(recall)을 확인하는 것이 중요하다.
#    재현율은 실제 심장병이 있는 사람 중 심장병이 있다고 올바르게 예측한 비율이다.
#    재현율만 높이면 FP가 늘 수 있으므로 정밀도(precision)와 총비용(5×FN + FP)도 확인한다.
#    05번의 평가 코드를 적용할 때는 target_names를 ["absent(0)", "present(1)"]로 바꾼다.
#    이 파일에서는 비용 행렬을 소개하며, 학습이나 예측에 적용하지는 않는다.
# ============================================================
COST = np.array([[0, 1],
                 [5, 0]])
print("\n오답의 상대적 비용 행렬 (행=실제 라벨, 열=예측 라벨):")
print("행과 열의 순서: absent(0)=심장병 없음, present(1)=심장병 있음")
print(COST)
print("심장병을 놓친 경우(FN): 비용 5, 없는 심장병을 있다고 예측한 경우(FP): 비용 1")

# ============================================================
# 7. 학습용 / 검증용 / 테스트용 분할 — 05번과 같은 60% / 20% / 20%
#    테스트 데이터는 54건이다. 정답 수가 1건 바뀌면 정확도는 약 1.9%p 달라진다.
#    stratify는 각 묶음의 클래스 비율을 원본과 최대한 비슷하게 유지한다.
#    random_state를 고정하면 같은 분할을 재현할 수 있다.
#    분할에 따른 변동은 학습·검증 데이터에서 교차 검증 등으로 확인한다.
#    테스트 데이터는 학습 설정을 정하는 데 사용하지 않고, 최종 평가용으로 남겨 둔다.
# ============================================================
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=10
)
X_train, X_val, y_train, y_val = train_test_split(
    X_train, y_train, test_size=0.25, stratify=y_train, random_state=10   # 0.8 × 0.25 = 0.2
)

print(f"\n데이터 분할 — 학습(train): {len(X_train)}건, "
      f"검증(validation): {len(X_val)}건, 테스트(test): {len(X_test)}건")
print("심장병 있음(present=1)의 비율 — "
      f"전체: {100 * y.mean():.1f}%, "
      f"학습: {100 * y_train.mean():.1f}%, "
      f"검증: {100 * y_val.mean():.1f}%, "
      f"테스트: {100 * y_test.mean():.1f}%")

# 다음 단계
#   이 분할에 05번의 코드(표준화 → 학습 → 조기 종료 → 평가)를 적용해 본다.
#   표준화 통계는 학습 데이터에서만 구하고, 평가 시 클래스 이름도 심장병 라벨로 바꾼다.
#   학습 손실은 낮아지는데 검증 손실이 다시 높아지는지 확인한다.
#   검증 손실이 가장 낮은 시점의 모델과 끝까지 학습한 모델의 결과를 비교해 본다.
#   최적 학습 횟수와 성능은 분할, 학습률, 정규화 여부에 따라 달라진다.
