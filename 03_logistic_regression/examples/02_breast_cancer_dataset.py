"""
scikit-learn 과 위스콘신 유방암 데이터셋 살펴보기
학습에 들어가기 전에, 앞으로 이진 분류 실습에 사용할 데이터를 먼저 이해한다.

scikit-learn(sklearn) 이란?
  파이썬의 대표적인 머신러닝 라이브러리.
  모델뿐 아니라 연습용 데이터셋(sklearn.datasets)과
  데이터 분할·평가 도구(sklearn.model_selection 등)도 함께 제공한다.
  이 수업에서는 모델은 직접 NumPy 로 구현하고,
  sklearn 에서는 "데이터"와 "도구"만 빌려 쓴다.

위스콘신 유방암 데이터셋 (Breast Cancer Wisconsin Diagnostic, 1995)
  장난감 데이터가 아니라 실제 병원에서 나온 데이터다.
  미국 위스콘신 대학병원의 외과 의사 Wolberg 박사가, 유방에 생긴 멍울에서
  가는 바늘로 세포를 뽑아(FNA, 세침흡인검사) 현미경 사진을 찍었다.
  그 사진 속 세포핵(nucleus)의 윤곽을 컴퓨터로 측정한 숫자 30개가 입력 x 이고,
  이후 확정된 진단 결과(악성/양성종양)가 정답 y 이다.

  → 풀어야 할 문제: "세포핵의 모양만 보고, 암인지 아닌지 맞힐 수 있을까?"
    의사가 현미경으로 하던 판단을, 우리가 만든 sigmoid 한 줄이 흉내 내는 것이다.
    암세포의 핵은 대체로 더 크고, 윤곽이 울퉁불퉁하다 — 5번에서 직접 확인한다.

왜 이진 분류 연습에 좋은가?
  1) 정답이 딱 두 가지(악성/양성종양)  → 이진 분류 그 자체
  2) 569건 × 30특성, 전부 실수, 결측치 없음 → 결측치 처리·범주형 인코딩이 필요 없다
     (단, 특성 크기를 맞추는 표준화는 필요 — 5번 참고)
  3) 작아서 NumPy 경사하강법으로도 몇 초면 끝난다
  4) 특성이 30개 → 01번 예제(D=1)를 다변수(D=30)로 그대로 확장해 볼 수 있다
  5) 특성마다 단위·크기가 제각각 → 02장에서 배운 표준화가 왜 필요한지 체감
  6) 로지스틱 회귀만으로도 정확도 95% 이상 → "내 모델이 진짜 된다"는 경험
  7) 오답의 무게가 다르다: 암을 놓치는 것 vs 정상을 암이라 하는 것
     → 정확도(accuracy)만으로 충분한가? 를 고민하게 해 준다
"""
import numpy as np
from sklearn import datasets
from sklearn.model_selection import train_test_split

# ============================================================
# 1. 데이터 불러오기
#    기본값으로 부르면 Bunch(딕셔너리처럼 쓰는 객체)가 반환된다.
#    데이터뿐 아니라 특성 이름, 클래스 이름, 설명문까지 들어 있다.
#    (X, y 만 필요하면 load_breast_cancer(return_X_y=True) 한 줄로 받을 수 있다.)
# ============================================================
ds = datasets.load_breast_cancer()
X, y = ds.data, ds.target

print("Bunch 의 키:", list(ds.keys()))
print(f"X: {X.shape}  (N=환자 검사 건수, D=특성 수)")
print(f"y: {y.shape}")
# print(ds.DESCR)   # 데이터셋 공식 설명문 전체 — 한 번쯤 읽어 볼 것

# ============================================================
# 2. 특성(feature) 30개의 구조
#    세포핵의 성질 10가지 × 통계 3가지(mean, error, worst) = 30개
#      성질: radius(반지름), texture(질감), perimeter(둘레), area(면적),
#            smoothness(매끄러움), compactness(조밀도), concavity(오목함),
#            concave points(오목한 점 수), symmetry(대칭성), fractal dimension
#      mean:  한 사진 속 핵들의 평균
#      error: 표준오차 (핵마다 값이 얼마나 들쭉날쭉한가)
#      worst: 각 특성에서 값이 가장 큰 핵 3개의 평균
# ============================================================
print("\n특성 이름:")
for i in range(0, 30, 10):
    print(" ", ", ".join(ds.feature_names[i:i + 10]))

# ============================================================
# 3. 정답(label) — 주의! 1 이 "암" 이 아니다
#      0 = malignant (악성, 암)
#      1 = benign    (양성종양, 암 아님)
#    한국어 "양성"은 良性(benign)과 陽性(positive, 검사 양성)이 같은 발음이라
#    헷갈리기 쉽다. 코드에서는 영어 이름을 함께 적는 습관을 들이자.
# ============================================================
print("\n클래스:")
for label, name in enumerate(ds.target_names):
    count = np.sum(y == label)
    print(f"  y={label}  {name:9s} {count:3d}건 ({100 * count / len(y):.1f}%)")

# ============================================================
# 4. 특성마다 크기(scale)가 크게 다르다
#    area 는 수천, smoothness 는 0.1 안팎 → 그대로 학습하면
#    큰 특성이 gradient 를 지배한다. (02장의 Feature Standardization 참고)
# ============================================================
print("\n특성별 값의 범위:")
for i in [0, 3, 4, 23]:
    print(f"  {ds.feature_names[i]:16s} {X[:, i].min():8.3f} ~ {X[:, i].max():8.3f}")

# ============================================================
# 5. 악성과 양성종양은 숫자로 구별이 될까?
#    클래스별 평균을 비교해 보면, 암세포의 핵이 더 크고 울퉁불퉁하다.
#    반면 fractal dimension 처럼 거의 차이가 없는 특성도 있다.
#    → 모델이 학습하는 w 는 결국 "어느 특성이 얼마나 중요한가" 이다.
# ============================================================
print("\n클래스별 평균 비교:")
print(f"  {'특성':22s} {'악성(0)':>10s} {'양성종양(1)':>10s}")
for i in [0, 3, 6, 9]:
    m0, m1 = X[y == 0, i].mean(), X[y == 1, i].mean()
    print(f"  {ds.feature_names[i]:24s} {m0:10.3f} {m1:10.3f}")

# ============================================================
# 6. 학습용 / 테스트용 분할
#    모델은 처음 보는 환자도 맞혀야 의미가 있다 → 일부를 떼어 시험용으로 남긴다.
#    stratify=y : 악성/양성종양 비율을 두 묶음에서 똑같이 유지한다.
#    random_state : 실행할 때마다 같은 결과가 나오도록 고정.
# ============================================================
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=10
)

print(f"\n학습 데이터: {len(X_train)}건, 테스트 데이터: {len(X_test)}건")
print("양성종양(1) 비율 — "
      f"전체: {100 * y.mean():.1f}%, "
      f"학습: {100 * y_train.mean():.1f}%, "
      f"테스트: {100 * y_test.mean():.1f}%")
