"""
Sonar 데이터셋 살펴보기 — 데이터 수에 비해 특성이 많은 이진 분류 문제
06번 심장병 데이터에 이어, 이번에는 음파의 반사 패턴으로 물체를 구분한다.
Sonar는 208건의 데이터에 특성이 60개여서 과적합을 관찰하는 실습에 적합하다.
특히 정규화 없이 오래 학습하면 학습 성능과 검증 성능의 차이가 커질 수 있다.
이 파일에서는 데이터를 탐색하고 분할한다. 모델 학습은 다음 실습에서 진행한다.

Sonar: Mines vs. Rocks (Gorman & Sejnowski, 1988)
  금속 원통과 원통 모양의 바위에 소나(음파)를 쏘아 얻은 반사 신호를 기록한 데이터다.
  각 기록에는 60개 주파수 대역에서 일정 시간 동안 측정한 에너지 값이 들어 있다.
  여러 각도와 조건에서 얻은 반사 패턴은 총 208건이며, 결측치는 없다.
  라벨은 Mine(금속 원통, 기뢰를 나타내는 클래스)과 Rock(바위) 두 가지다.
  원래 신경망의 물체 구분 성능을 연구하는 데 사용되었다.

  → 풀어야 할 문제: "60개 대역의 에너지 값으로 바위와 금속 원통을 구분할 수 있을까?"

왜 과적합을 살펴보기 좋은가?
  60%를 학습용으로 사용한다고 가정하면, 가중치와 편향 하나당 학습 기록 수는 대략
  유방암 11건, 심장병 12건, Sonar 2건이다. 구체적인 계산은 아래 5번에서 확인한다.
  Sonar는 상대적으로 적은 기록으로 많은 가중치를 학습해야 하므로,
  학습 데이터의 우연한 패턴까지 맞추고 새로운 데이터에서는 성능이 떨어질 수 있다.
  다만 이 비율만으로 과적합을 단정할 수는 없다. 특성 간 관계, 정규화 여부,
  데이터 분할과 학습 횟수도 영향을 준다. 실제 과적합 여부는 검증 손실로 확인한다.

이 데이터의 또 다른 특징
  1) 특성 이름은 대역 번호다: OpenML에서는 attribute_1 ~ attribute_60으로 제공한다.
     심장병 데이터처럼 개별 특성의 의미가 구체적이지 않아도 여러 대역의 조합으로
     두 클래스를 구분하는 패턴을 학습할 수 있다.
  2) 값은 모두 0.0~1.0 범위지만 대역별 평균과 퍼짐은 다르다.
     같은 범위의 값이라도 경사하강법으로 학습할 때 표준화가 도움이 될 수 있다.
  3) 기뢰 탐지를 가정하면 Mine을 Rock으로 예측한 경우(FN)를 줄이는 것이 중요하다.
     Mine을 관심 클래스(1)로 정하고 정확도와 함께 재현율(recall)을 확인한다.
     이 예제의 실험 데이터와 실제 기뢰 탐지 환경은 구분해서 이해한다.

데이터셋 설명: https://archive.ics.uci.edu/dataset/151/connectionist+bench+sonar+mines+vs+rocks
"""
import numpy as np
from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split

# ============================================================
# 1. 데이터 불러오기 — 06번과 같이 OpenML 사용
#    version=1로 버전을 지정하고, as_frame=True로 열 이름이 있는 DataFrame을 받는다.
# ============================================================
ds = fetch_openml("sonar", version=1, as_frame=True)
X_df, y_raw = ds.data, ds.target

print(f"입력 X의 형태: {X_df.shape}  (행=반사 패턴 수, 열=주파수 대역 수)")
print(f"원본 라벨 y의 형태: {y_raw.shape}  라벨 종류: {list(y_raw.unique())}")
print(f"특성 이름: {X_df.columns[0]}, {X_df.columns[1]}, ..., {X_df.columns[-1]}")
# print(ds.DESCR)   # 실험 배경과 원 논문의 방법이 자세히 적혀 있다

# ============================================================
# 2. 정답(label) — OpenML의 문자열 라벨을 0/1로 변환
#      "Rock" → 0 (바위)
#      "Mine" → 1 (금속 원통, 기뢰 클래스)  ← 관심 클래스(positive class)
#    UCI 원본의 R/M 표기와 OpenML의 Rock/Mine 표기는 다르므로 실제 라벨을 확인한다.
#    recall_score의 기본값(pos_label=1)으로 Mine의 재현율을 계산할 수 있다.
# ============================================================
y = (y_raw == "Mine").astype(int).to_numpy()
X = X_df.to_numpy(dtype=float)

print("\n변환한 라벨별 기록 수와 비율:")
for label, name in [(0, "Rock (바위)"), (1, "Mine (금속 원통, 기뢰 클래스)")]:
    count = np.sum(y == label)
    print(f"  y={label}  {name}: {count:3d}건 ({100 * count / len(y):.1f}%)")

# ============================================================
# 3. 특성 60개 — 대역마다 값의 분포가 다르다
#    값은 모두 0~1 범위지만, 대역마다 평균과 값의 범위가 다르다.
#    대역별 규모 차이는 가중치의 업데이트에 영향을 줄 수 있어 표준화를 사용한다.
#    표준화 통계는 분할 후 학습 데이터에서만 구하고, 검증·테스트 데이터에도 적용한다.
#    아래 출력은 전체 데이터의 일부 대역을 살펴보는 탐색용 통계다.
# ============================================================
print("\n일부 대역의 최솟값·최댓값·평균 (전체 데이터 기준):")
for i in [0, 10, 30, 59]:
    col = X[:, i]
    print(f"  attribute_{i + 1:<3d} 최솟값 {col.min():.3f}, 최댓값 {col.max():.3f}, 평균 {col.mean():.3f}")

# ============================================================
# 4. 바위와 금속 원통은 대역별 평균 에너지가 다를까?
#    각 클래스의 평균을 구하고, 1, 7, 13, ...번 대역을 텍스트 막대로 표시한다.
#    막대는 ■ 하나당 에너지 0.05이며, 0.05 미만의 나머지는 생략한다.
#    평균 차이가 크더라도 개별 기록의 분포가 겹칠 수 있으므로,
#    평균만으로 특정 대역의 분류 성능을 판단할 수는 없다.
# ============================================================
mean_rock = X[y == 0].mean(axis=0)   # 바위 기록의 대역별 평균: 형태 (60,)
mean_mine = X[y == 1].mean(axis=0)   # 금속 원통 기록의 대역별 평균: 형태 (60,)

print("\n클래스별 평균 에너지 (6개 대역 간격으로 표시, ■ 하나 = 0.05, 나머지는 생략):")
print("  Rock(0)=바위, Mine(1)=금속 원통(기뢰 클래스)")
print(f"  {'대역':4s} {'Rock(0)':24s} {'Mine(1)':24s}")
for i in range(0, 60, 6):
    bar_rock = "■" * int(mean_rock[i] / 0.05)
    bar_mine = "■" * int(mean_mine[i] / 0.05)
    print(f"  {i + 1:<6d} {bar_rock:24s} {bar_mine:24s}")

diff = mean_mine - mean_rock   # 양수: Mine 평균이 더 큼, 음수: Rock 평균이 더 큼
top = np.argsort(np.abs(diff))[::-1][:4]   # 평균 차이의 절댓값이 큰 대역 4개
print("\n평균 차이의 절댓값이 가장 큰 대역 4개 (차이 = Mine 평균 - Rock 평균):")
for i in top:
    print(f"  attribute_{i + 1:<3d} Rock 평균 {mean_rock[i]:.3f}  Mine 평균 {mean_mine[i]:.3f}  차이 {diff[i]:+.3f}")

# ============================================================
# 5. 파라미터 하나당 학습 기록은 몇 건일까? — 데이터 수와 모델 크기 비교
#    특성이 D개인 이진 로지스틱 회귀는 가중치 D개와 편향 1개를 학습한다.
#    전체 기록 수의 60%를 정수로 내림하여 학습 기록 수를 대략 비교한다.
#    실제 두 단계 분할에서는 묶음별 건수를 정수로 맞추므로 이 추정값과 다를 수 있다.
#    이 비율은 과적합 위험을 생각해 보는 참고값이며, 과적합 여부를 판정하는 기준은 아니다.
# ============================================================
print("\n파라미터 하나당 학습 기록 수 (전체의 60%를 내림한 추정값):")
for name, n, d in [("유방암", 569, 30), ("심장병", 270, 13), ("Sonar", 208, 60)]:
    n_train = int(n * 0.6)
    print(f"  {name}: 학습 약 {n_train:3d}건 / 파라미터 {d + 1:2d}개 = 파라미터당 약 {n_train / (d + 1):.1f}건")

# ============================================================
# 6. 학습용 / 검증용 / 테스트용 분할 — 05, 06번과 같이 약 60% / 20% / 20%
#    실제 분할은 학습 124건, 검증 42건, 테스트 42건이다.
#    검증·테스트에서 정답 수가 1건 바뀌면 정확도는 약 2.4%p 달라진다.
#    stratify는 클래스 비율을 최대한 유지하고, random_state는 같은 분할을 재현하게 한다.
#    데이터가 적으므로 학습·검증 데이터에서 교차 검증 등으로 성능의 변동을 확인한다.
#    테스트 데이터는 학습 설정을 정하는 데 사용하지 않고, 최종 평가용으로 남겨 둔다.
# ============================================================
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=10
)
X_train, X_val, y_train, y_val = train_test_split(
    X_train, y_train, test_size=0.25, stratify=y_train, random_state=10   # 0.8 × 0.25 = 0.2
)

print(f"\n데이터 분할 — 학습(train): {len(X_train)}건, "
      f"검증(validation): {len(X_val)}건, 테스트(test): {len(X_test)}건")
print("금속 원통(Mine=1)의 비율 — "
      f"전체: {100 * y.mean():.1f}%, "
      f"학습: {100 * y_train.mean():.1f}%, "
      f"검증: {100 * y_val.mean():.1f}%, "
      f"테스트: {100 * y_test.mean():.1f}%")

# 다음 단계 — 08번에서 한다
#   이 분할에 05번의 코드(표준화 → 학습 → 조기 종료 → 평가)를 적용해 본다.
#   표준화 통계는 학습 데이터에서만 구하고, target_names는 ["Rock(0)", "Mine(1)"]로 바꾼다.
#   학습 손실과 검증 손실을 나란히 기록해 두 값이 어떻게 달라지는지 살펴본다.
#   학습 손실은 계속 낮아지는데 검증 손실이 높아지면 과적합의 신호다.
#   학습 정확도가 높아져도 새로운 데이터에서 같은 성능을 낸다는 뜻은 아니다.
#   검증 손실이 가장 낮은 모델과 끝까지 학습한 모델을 비교하고, Mine의 재현율도 확인한다.
#   손실의 구체적인 값과 최적 학습 횟수는 분할, 학습률, 정규화 여부에 따라 달라진다.
