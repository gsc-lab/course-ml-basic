"""
Sonar 데이터셋 살펴보기 — 과적합의 교과서
06번 심장병 데이터는 "적당히 어려운" 문제였다. 과적합도 분명히 보이지만 폭이 크지 않다.
이번 데이터는 다르다. 로지스틱 회귀가 train 을 100% 외워 버리고,
validation loss 는 최저점의 3배까지 치솟는다. 과적합을 보여주기 위한 데이터라 해도 된다.

Sonar: Mines vs. Rocks (Gorman & Sejnowski, 1988)
  바다 밑에 놓인 금속 원통(기뢰 모형)과 비슷한 크기의 바위에 소나(음파)를 쏘고,
  되돌아온 반사파를 60개 주파수 대역으로 나눠 각 대역의 에너지를 기록했다.
  여러 각도에서 쏜 208개의 반사파 패턴이 있고, 정답은 기뢰(Mine) / 바위(Rock).
  원래는 신경망 성능을 시험하려고 만든 데이터다 — 신경망 단원에서 다시 만나게 된다.

  → 풀어야 할 문제: "반사 음파의 스펙트럼만 보고, 바위인지 기뢰인지 가려낼 수 있을까?"

왜 과적합이 이렇게 잘 일어나나? (train 60% 기준)
  유방암:  train 341건,  파라미터 31개  → 파라미터 하나당 데이터 11건
  심장병:  train 162건,  파라미터 14개  → 파라미터 하나당 데이터 12건
  sonar:   train 124건,  파라미터 61개  → 파라미터 하나당 데이터  2건
  파라미터가 데이터의 절반이면, 일반적인 규칙을 찾는 대신 train 124건을 하나하나
  외우는 쪽이 loss 를 더 빨리 줄인다. 모델은 그 길을 택한다.

이 데이터의 또 다른 특징
  1) 특성에 이름이 없다: attribute_1 ~ attribute_60. 그냥 "대역 1~60 의 에너지" 다.
     특성의 의미를 몰라도 모델은 패턴을 찾는다 — 그것이 ML 의 본질이기도 하다.
  2) 값이 전부 0.0~1.0 사이라 단위는 같다. 하지만 대역마다 분포가 달라서
     (1번 대역은 0.14 를 못 넘고, 31번 대역은 0.97 까지 간다) 표준화는 여전히 한다.
  3) 정확도가 75~80% 에서 멈춘다. 틀리는 쪽은 기뢰를 바위로 보는 것(FN)이 치명적이다.
     Mine = 1 = Positive 로 두고 recall 을 본다.
"""
import numpy as np
from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split

# ============================================================
# 1. 데이터 불러오기 — 06번과 같이 OpenML 에서
# ============================================================
ds = fetch_openml("sonar", version=1, as_frame=True)
X_df, y_raw = ds.data, ds.target

print(f"X: {X_df.shape}  (N=반사파 패턴 수, D=주파수 대역 수)")
print(f"y: {y_raw.shape}  값의 종류: {list(y_raw.unique())}")
print(f"특성 이름: {X_df.columns[0]}, {X_df.columns[1]}, ... , {X_df.columns[-1]}")
# print(ds.DESCR)   # 실험 배경과 원 논문의 방법이 자세히 적혀 있다

# ============================================================
# 2. 정답(label) — 문자열을 0/1 로
#      "Rock" → 0 (바위)
#      "Mine" → 1 (기뢰)  ← Positive. 놓치면 안 되는 쪽
# ============================================================
y = (y_raw == "Mine").astype(int).to_numpy()
X = X_df.to_numpy(dtype=float)

print("\n클래스:")
for label, name in [(0, "Rock"), (1, "Mine")]:
    count = np.sum(y == label)
    print(f"  y={label}  {name:5s} {count:3d}건 ({100 * count / len(y):.1f}%)")

# ============================================================
# 3. 특성 60개 — 대역마다 값의 분포가 다르다
#    전부 0~1 사이지만, 낮은 대역과 높은 대역은 에너지가 거의 없고
#    중간 대역(20~40번)에 에너지가 몰려 있다. 표준화 없이 쓰면 중간 대역만 학습을 지배한다.
# ============================================================
print("\n대역별 값의 범위:")
for i in [0, 10, 30, 59]:
    col = X[:, i]
    print(f"  attribute_{i + 1:<3d} {col.min():.3f} ~ {col.max():.3f}  (평균 {col.mean():.3f})")

# ============================================================
# 4. 바위와 기뢰는 스펙트럼이 다를까? — 클래스별 평균 스펙트럼
#    대역 6개 간격으로 두 클래스의 평균 에너지를 막대로 그린다.
#    기뢰(금속)는 20~25번 대역에서 더 강하게, 35~40번 대역에서 더 약하게 반사된다.
#    하지만 겹치는 대역이 훨씬 많다 — 사람 눈으로는 구별이 어렵다.
# ============================================================
mean_rock = X[y == 0].mean(axis=0)   # (60,)
mean_mine = X[y == 1].mean(axis=0)   # (60,)

print("\n클래스별 평균 에너지 (■ = 0.05):")
print(f"  {'대역':6s} {'Rock(0)':24s} {'Mine(1)':24s}")
for i in range(0, 60, 6):
    bar_rock = "■" * int(mean_rock[i] / 0.05)
    bar_mine = "■" * int(mean_mine[i] / 0.05)
    print(f"  {i + 1:<6d} {bar_rock:24s} {bar_mine:24s}")

diff = mean_mine - mean_rock
top = np.argsort(np.abs(diff))[::-1][:4]
print("\n두 클래스의 평균 차이가 큰 대역:")
for i in top:
    print(f"  attribute_{i + 1:<3d} Rock {mean_rock[i]:.3f}  Mine {mean_mine[i]:.3f}  (차이 {diff[i]:+.3f})")

# ============================================================
# 5. 파라미터 하나당 데이터 몇 건? — 과적합이 일어나는 조건
#    train 을 60% 로 잡았을 때의 건수를 세 데이터셋에 대해 계산해 본다.
#    이 비율이 작을수록 모델은 규칙을 찾는 대신 데이터를 외운다.
# ============================================================
print("\n파라미터 하나당 train 데이터 건수 (train 60% 기준):")
for name, n, d in [("유방암", 569, 30), ("심장병", 270, 13), ("sonar", 208, 60)]:
    n_train = int(n * 0.6)
    print(f"  {name:6s} train {n_train:3d}건 / 파라미터 {d + 1:2d}개 = {n_train / (d + 1):5.1f} 건")

# ============================================================
# 6. 학습용 / 검증용 / 테스트용 분할 — 05, 06번과 같은 60% / 20% / 20%
#    validation 과 test 가 각각 42건이다. 패턴 하나가 정확도 2.4%p 를 움직인다.
# ============================================================
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=10
)
X_train, X_val, y_train, y_val = train_test_split(
    X_train, y_train, test_size=0.25, stratify=y_train, random_state=10   # 0.8 × 0.25 = 0.2
)

print(f"\ntrain: {len(X_train)}건, validation: {len(X_val)}건, test: {len(X_test)}건")
print("Mine(1) 비율 — "
      f"전체: {100 * y.mean():.1f}%, "
      f"train: {100 * y_train.mean():.1f}%, "
      f"validation: {100 * y_val.mean():.1f}%, "
      f"test: {100 * y_test.mean():.1f}%")

